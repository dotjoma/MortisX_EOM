// GetExpNeed returns the required EXP to advance from level `lv` to `lv+1`.
// Matches GD.exp_need(lv) in gamedata.gd:73.
func GetExpNeed(lv int) int64 {
	if lv < 1 {
		lv = 1
	}
	idx := lv + 1
	if idx >= len(flyffExpTable) {
		idx = len(flyffExpTable) - 1
	}
	return flyffExpTable[idx][0]
}
